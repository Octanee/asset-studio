"""Application settings, read from environment variables prefixed with ``ASSET_STUDIO_``."""

from functools import lru_cache
from typing import Annotated, Literal

from pydantic import field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="ASSET_STUDIO_", env_file=".env", extra="ignore")

    # Loopback by default (NFR-005). Containers override this and publish only on 127.0.0.1.
    host: str = "127.0.0.1"
    port: int = 8400
    database_url: str = "postgresql+psycopg://asset_studio:asset_studio@127.0.0.1:5432/asset_studio"
    data_dir: str = "./data"
    log_level: str = "INFO"
    log_json: bool = True

    # Security (ADR-012). Host names accepted in the Host header and in Origin.
    allowed_hosts: Annotated[list[str], NoDecode] = ["127.0.0.1", "localhost", "[::1]"]
    # Per-install secrets, generated by setup. Empty token = that credential is disabled.
    session_secret: str = ""
    mcp_token: str = ""
    worker_token: str = ""

    # Generation engine (ADR-005, ADR-006). ComfyUI and the host agent run natively on the
    # host; containers reach them as host.docker.internal. "fake" serves CI and UI work.
    engine_provider: Literal["comfyui", "fake"] = "comfyui"
    comfyui_url: str = "http://127.0.0.1:8188"
    host_agent_url: str = "http://127.0.0.1:8410"
    host_agent_token: str = ""
    engine_health_ttl_seconds: float = 5.0
    # DWPose model files (ADR-009); empty means <data_dir>/models/pose.
    pose_models_dir: str = ""
    # Model folders in the ComfyUI layout (checkpoints, loras, ...); empty means <data_dir>/models.
    models_dir: str = ""
    # Folders publishing may write into (ADR-013): bind mounts of Windows folders. Every export
    # target lives under one of them. Empty = publishing is not configured.
    export_roots: Annotated[list[str], NoDecode] = []
    # Where backups are written and restored from (FR-111): a bind mount of a Windows folder in
    # compose, so a backup lives outside Docker (ADR-013). Empty means <data_dir>/backups.
    backups_dir: str = ""
    # Port of the MCP server on the host, shown in Settings > MCP connection.
    mcp_port: int = 8411

    @field_validator("allowed_hosts", "export_roots", mode="before")
    @classmethod
    def _split_hosts(cls, value: object) -> object:
        if isinstance(value, str):
            return [h.strip() for h in value.split(",") if h.strip()]
        return value


@lru_cache
def get_settings() -> Settings:
    return Settings()
